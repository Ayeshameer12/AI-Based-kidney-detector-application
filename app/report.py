"""
report.py
---------
Generates the downloadable PDF report: prediction summary, confidence
score, original image, and Grad-CAM heatmap — matching the proposal's
"Report Generation Module" requirement.
"""

import io
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import cm
from reportlab.lib import colors
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Image as RLImage, Table, TableStyle
)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle


def generate_pdf_report(data: dict) -> io.BytesIO:
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4, topMargin=2 * cm, bottomMargin=2 * cm)
    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "TitleCustom", parent=styles["Title"], fontSize=18, spaceAfter=6
    )
    subtitle_style = ParagraphStyle(
        "Subtitle", parent=styles["Normal"], fontSize=10, textColor=colors.grey
    )
    section_style = ParagraphStyle(
        "Section", parent=styles["Heading2"], fontSize=13, spaceBefore=14, spaceAfter=6
    )
    disclaimer_style = ParagraphStyle(
        "Disclaimer", parent=styles["Normal"], fontSize=8, textColor=colors.grey, spaceBefore=20
    )

    elements = []
    elements.append(Paragraph("Kidney Image Analysis Report", title_style))
    elements.append(Paragraph(f"Generated on {data['timestamp']}", subtitle_style))
    elements.append(Spacer(1, 0.5 * cm))

    # Result table
    verdict_color = colors.HexColor("#B84C3C") if data["label"] == "Abnormal" else colors.HexColor("#2F6B4F")
    result_table_data = [
        ["Prediction", data["label"]],
        ["Confidence", f"{data['confidence']}%"],
    ]
    result_table = Table(result_table_data, colWidths=[6 * cm, 6 * cm])
    result_table.setStyle(TableStyle([
        ("FONTSIZE", (0, 0), (-1, -1), 11),
        ("TEXTCOLOR", (1, 0), (1, 0), verdict_color),
        ("FONTNAME", (1, 0), (1, 0), "Helvetica-Bold"),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
        ("TOPPADDING", (0, 0), (-1, -1), 8),
        ("LINEBELOW", (0, 0), (-1, 0), 0.5, colors.lightgrey),
        ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#E0E0E0")),
    ]))
    elements.append(result_table)

    # Images
    elements.append(Paragraph("Original image", section_style))
    if data.get("original_path"):
        elements.append(RLImage(data["original_path"], width=8 * cm, height=8 * cm))

    if data.get("heatmap_path"):
        elements.append(Paragraph("Model attention heatmap (Grad-CAM)", section_style))
        elements.append(Paragraph(
            "The highlighted region shows which part of the image most influenced the model's prediction.",
            styles["Normal"]
        ))
        elements.append(Spacer(1, 0.2 * cm))
        elements.append(RLImage(data["heatmap_path"], width=8 * cm, height=8 * cm))

    elements.append(Paragraph(
        "Disclaimer: This report is generated by an academic research tool developed as part of a "
        "Final Year Project. It is not a certified medical device and must not be used as a substitute "
        "for professional medical diagnosis. Please consult a qualified radiologist or physician for "
        "clinical decisions.",
        disclaimer_style
    ))

    doc.build(elements)
    buffer.seek(0)
    return buffer
